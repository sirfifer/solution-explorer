    lines = [
        f"# {report['subject']['name']} demo run: {report['date']}",
        "",
        f"- slug: `{report['slug']}`",
        f"- status: **{report['status']}**",
        f"- resolved commit: `{report.get('resolved_sha') or 'unknown'}` ({report.get('resolved_ref') or 'unresolved'})",
        f"- hosting: {report['hosting'].get('url')}",
        "",
        "## Stats",
        "",
    ]
    for key, value in report.get("stats", {}).items():
        lines.append(f"- {key}: {value}")
    lines += ["", "## Coverage summary", ""]
    for disp, count in report.get("coverage_summary", {}).items():
        lines.append(f"- {disp}: {count}")
