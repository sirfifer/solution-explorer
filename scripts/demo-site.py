def _snapshot_history(slug: str, out_dir: Path, corpus_dir: Optional[Path] = None) -> None:
    """Copy today's manifest.json into _out/<slug>/history/<date>/ so a later
    `diff` has something to compare a future run against. Gitignored cache only
    (never committed): the committed record of a diff is the diff itself
    (demos/runs/<slug>/<date>/diff.json), not the raw projections either side
    used, which would bloat the repo every week for no reviewing benefit."""
    manifest = out_dir / "manifest.json"
    if not manifest.is_file():
        return
    dest_dir = _out_dir(slug, corpus_dir) / "history" / _today()
    dest_dir.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(manifest, dest_dir / "manifest.json")


def run_analyze(corpus: dict, corpus_dir: Optional[Path] = None) -> float:
    """`analyze.py <src> -o <out> --split --engine v2 --store <per-demo store>`.

    Returns wall time in seconds. `budget.max_wall_minutes` is enforced as a
    subprocess timeout (not specified explicitly in DEMO-PROGRAM.md 4.2, but
    the registry carries the field and section 4.6/7 treat wall time as a real
    constraint to measure and budget against, so bounding it here is the
    natural place).
    """
    slug = corpus["slug"]
    src = _src_dir(slug, corpus_dir)
    if not (src / ".git").exists():
        raise FileNotFoundError(f"no fetched corpus for '{slug}' at {src}; run: fetch {slug}")
    out_dir = _arch_dir(slug, corpus_dir)
    store_path = _store_path(slug, corpus_dir)
    minutes = corpus.get("budget", {}).get("max_wall_minutes")
    timeout_s = float(minutes) * 60 if minutes else None

    cmd = [
        sys.executable, str(ANALYZE_SCRIPT), str(src),
        "-o", str(out_dir), "--split", "--engine", "v2", "--store", str(store_path),
    ]
    t0 = time.perf_counter()
    subprocess.run(cmd, check=True, timeout=timeout_s)
    wall_s = time.perf_counter() - t0
    _snapshot_history(slug, out_dir, corpus_dir)
    return wall_s


def run_enhance(
    corpus: dict,
    corpus_dir: Optional[Path] = None,
    *,
    max_partitions: Optional[int] = None,
    dry_run: bool = False,
) -> int:
    """`analyze.py enhance --update` with the registry's cost ceiling and
    quality threshold. Returns the subprocess exit code (0 success/dry-run, 1 a
    real but non-crashing failure such as a failed partition or an unmet
    quality gate) rather than raising, so a caller can decide what a
    "successful enhance run that failed its own gate" means without catching
    an exception for an expected outcome.

    `--threshold` is not in the DEMO-PROGRAM.md 4.2 one-liner for this
    subcommand, but wiring it from `gates.min_enrichment_score` means the
    quality gate `analyze.py enhance` already computes is directly what
    `validate`'s enrichment gate reads back, instead of re-implementing the
    scorer a second time.
    """
    slug = corpus["slug"]
    root = _src_dir(slug, corpus_dir)
    store_path = _store_path(slug, corpus_dir)
    if not store_path.exists():
        raise FileNotFoundError(f"no fact store for '{slug}' at {store_path}; run: analyze {slug}")
    report_path = _out_dir(slug, corpus_dir) / "enhance-report.json"

    cmd = [
        sys.executable, str(ANALYZE_SCRIPT), "enhance", str(root),
        "--store", str(store_path),
        "--update",
        "--max-cost-usd", str(corpus["budget"]["max_cost_usd"]),
        "--threshold", str(corpus["gates"]["min_enrichment_score"]),
        "--report", str(report_path),
    ]

    # The Enrichment Engine ladder, when the registry asks for it. The Run Report
    # lands in the run directory beside every other artifact of that refresh, so
    # a reader who opens one date opens everything that happened on it.
    enrichment = corpus.get("enrichment") or {}
    if enrichment.get("pipeline") == "ladder":
        run_dir = _run_dir(slug, runs_dir=None) / "enrichment"
        cmd += ["--ladder", "--run-dir", str(run_dir)]
        for key, binding in sorted((enrichment.get("models") or {}).items()):
            cmd += ["--phase-model", f"{key}={binding}"]
        iteration = enrichment.get("iteration") or {}
        if iteration.get("min_rounds") is not None:
            cmd += ["--min-rounds", str(iteration["min_rounds"])]
        if iteration.get("max_rounds") is not None:
            cmd += ["--max-rounds", str(iteration["max_rounds"])]

    if max_partitions is not None:
        cmd += ["--max-partitions", str(max_partitions)]
    if dry_run:
        cmd += ["--dry-run"]

    result = subprocess.run(cmd)
    return result.returncode


def enrichment_run_dir(slug: str, date: Optional[str] = None, runs_dir: Optional[Path] = None) -> Path:
    """Where a ladder run's Run Report lands for one demo and date."""
    return _run_dir(slug, date=date, runs_dir=runs_dir) / "enrichment"


