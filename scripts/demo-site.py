# bundle: assemble the DEPLOYABLE artifact
# ---------------------------------------------------------------------------
#
# The projection output directory is NOT a deployable site. It is data:
# manifest.json, data/, search/, ai.json, llms.txt. Deploying it directly would
# publish the raw architecture JSON with no viewer to read it and, far worse,
# with no `functions/_middleware.js`, which means no preview gate at all. A
# "private preview" assembled that way is fully public, which is exactly what
# DISCLOSURE-POLICY.md step 3 forbids ("Deploy gated, never public.
# Client-side-only gating is theater and is not acceptable").
#
# DEMO-PROGRAM.md 4.2 does not list a bundle step between `analyze` and
# `deploy`; that is a gap in the written design, recorded here rather than
# papered over. This is the missing step, and it mirrors what action.yml already
# does in CI: projection into viewer/public/architecture, viewer build, deploy
# the built dist.


def _bundle_dir(slug: str, corpus_dir: Optional[Path] = None) -> Path:
    return _out_dir(slug, corpus_dir) / "bundle"


VIEWER_DIR = REPO_ROOT / "viewer"
PREVIEW_GATE_MIDDLEWARE = REPO_ROOT / "infrastructure" / "preview-gate" / "_middleware.js"

# Upstream files worth carrying into the bundle beside UPSTREAM-LICENSE.txt.
# LICENSE-REVIEW.md step 4 asks for the NOTICE analogue; VS Code ships
# ThirdPartyNotices.txt rather than a file literally called NOTICE.
UPSTREAM_LICENSE_CANDIDATES = ("LICENSE", "LICENSE.txt", "LICENSE.md", "COPYING")
UPSTREAM_NOTICE_CANDIDATES = ("NOTICE", "NOTICE.txt", "ThirdPartyNotices.txt")


def _find_first(src: Path, names: tuple) -> Optional[Path]:
    for name in names:
        candidate = src / name
        if candidate.is_file():
            return candidate
    return None


def assemble_bundle(
    corpus: dict,
    *,
    corpus_dir: Optional[Path] = None,
    build: bool = True,
) -> Path:
    """Assemble the deployable bundle for ``corpus`` and return its path.

    Steps, in the order action.yml does them:

      1. copy the split projection into viewer/public/architecture/
      2. build the viewer (vite) into viewer/dist
      3. copy viewer/dist to the bundle directory
      4. install the preview gate as functions/_middleware.js
      5. ship the upstream LICENSE as UPSTREAM-LICENSE.txt, plus any NOTICE
      6. carry publication.json through if the projection produced one

    ``build=False`` skips the npm build and reuses an existing viewer/dist,
    which is what the tests use; it never skips steps 4 and 5, because those are
    the obligations, not the expensive part.
    """
    slug = corpus["slug"]
    arch_dir = _arch_dir(slug, corpus_dir)
    if not (arch_dir / "manifest.json").is_file():
        raise RuntimeError(f"no projection at {arch_dir}; run: analyze {slug}")

    bundle = _bundle_dir(slug, corpus_dir)

    # 1. build the viewer AS-IS. Deliberately NOT by copying the projection into
    # viewer/public/architecture first, which is the obvious move and is wrong:
    # that directory is 259 TRACKED files (the committed UnaMentis dataset), so
    # writing a subject's projection over it would destroy repository content and
    # produce an enormous spurious diff. action.yml sidesteps this in CI by
    # building a copy of the viewer under .solution-explorer/. Here the projection
    # is swapped into the BUILT output instead, at step 3, which touches nothing
    # tracked and costs only a build against the placeholder dataset.
    if build:
        subprocess.run(["npm", "run", "build"], cwd=str(VIEWER_DIR), check=True)

    dist = VIEWER_DIR / "dist"
    if not (dist / "index.html").is_file():
        raise RuntimeError(
            f"viewer build produced no index.html at {dist}; a bundle without a "
            f"viewer is raw JSON, not a demo"
        )

    # 2. dist -> bundle
    if bundle.exists():
        shutil.rmtree(bundle, ignore_errors=True)
    shutil.copytree(dist, bundle)

    # 3. swap the placeholder dataset for this subject's projection
    bundled_arch = bundle / "architecture"
    if bundled_arch.exists():
        shutil.rmtree(bundled_arch, ignore_errors=True)
    shutil.copytree(arch_dir, bundled_arch)

    # 4. the preview gate. Copied ALWAYS, not only for private previews: a gate
    # present but unconfigured denies everything (its own README: "Without it
    # the gate denies everything"), which is the safe direction. A gate absent
    # opens everything.
    if not PREVIEW_GATE_MIDDLEWARE.is_file():
        raise RuntimeError(f"preview gate middleware missing at {PREVIEW_GATE_MIDDLEWARE}")
    functions_dir = bundle / "functions"
    functions_dir.mkdir(parents=True, exist_ok=True)
    shutil.copy2(PREVIEW_GATE_MIDDLEWARE, functions_dir / "_middleware.js")

    # 5. upstream license and notice (LICENSE-REVIEW.md steps 3 and 4)
    src = _src_dir(slug, corpus_dir)
    lic = _find_first(src, UPSTREAM_LICENSE_CANDIDATES)
    if lic is None:
        raise RuntimeError(
            f"no upstream license file found in {src} (looked for "
            f"{list(UPSTREAM_LICENSE_CANDIDATES)}); the bundle redistributes "
            f"upstream text and the notice must travel with it"
        )
    shutil.copy2(lic, bundle / "UPSTREAM-LICENSE.txt")
    notice = _find_first(src, UPSTREAM_NOTICE_CANDIDATES)
    if notice is not None:
        shutil.copy2(notice, bundle / notice.name)

    # 6. publication.json, if the projection carries one
    pub = arch_dir / "publication.json"
    if pub.is_file():
        shutil.copy2(pub, bundle / "publication.json")

    return bundle


def bundle_safety_errors(bundle: Path) -> list:
    """Return the reasons ``bundle`` must not be deployed. Empty means safe.

    This is the last line before an outward-facing action, so it re-checks the
    obligations against the assembled directory rather than trusting that
    assemble_bundle ran. Anything here is a hard refusal, never a warning.
    """
    errors = []
    if not bundle.is_dir():
        return [f"no bundle at {bundle}; run: bundle <slug>"]
    if not (bundle / "index.html").is_file():
        errors.append(
            f"no index.html in {bundle}: this is raw projection data, not a viewer"
        )
    if not (bundle / "functions" / "_middleware.js").is_file():
        errors.append(
            f"no functions/_middleware.js in {bundle}: the preview gate would be "
            f"absent and the deployment fully public (DISCLOSURE-POLICY.md step 3)"
        )
    if not any((bundle / n).is_file() for n in UPSTREAM_LICENSE_NAMES):
        errors.append(
            f"no upstream license in {bundle}: the bundle redistributes upstream "
            f"text (LICENSE-REVIEW.md step 3)"
        )
    return errors


