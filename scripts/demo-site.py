def finding_fingerprint(slug: str, check: str, detail: str) -> str:
    """`demo-finding:<slug>:<check>:<hash>` per 5.2, stable across runs for the
    same (slug, check, detail) and different whenever any of them differ."""
    digest = hashlib.sha256(detail.encode("utf-8")).hexdigest()[:12]
    return f"demo-finding:{slug}:{check}:{digest}"


def _zero_symbol_findings(slug: str, corpus_dir: Optional[Path]) -> list[dict]:
    """5.1: zero-symbol components in a full-parse language (a parser finding)."""
    arch_dir = _arch_dir(slug, corpus_dir)
    manifest_path = arch_dir / "manifest.json"
    if not manifest_path.is_file():
        return []
    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return []
    index = manifest.get("component_detail_index") or {}
    zero_ids = [
        c["id"] for c in _iter_components(manifest.get("components"))
        if c.get("language") in FULL_PARSE_LANGS
        and (index.get(c.get("id")) or {}).get("symbolCount", 0) == 0
        and c.get("id") in index
    ]
    if not zero_ids:
        return []
    detail = f"{len(zero_ids)} full-parse-language component(s) with zero symbols, e.g. {sorted(zero_ids)[:5]}"
    return [{
        "check": "zero_symbol_full_parse_components",
        "severity": "finding",
        "summary": detail,
        "fingerprint": finding_fingerprint(slug, "zero_symbol_full_parse_components", detail),
    }]


def _orphan_share_finding(slug: str, corpus_dir: Optional[Path]) -> list[dict]:
    """5.1: orphan share, components with no relationships (a relationship-
    inference finding). No numeric floor is given in DEMO-PROGRAM.md for this
    one (unlike coverage/detect-only/enrichment, it is a finding, not a
    graduation gate), so 10% is a documented, conservative noise floor below
    which it is not worth a finding every single week."""
    arch_dir = _arch_dir(slug, corpus_dir)
    manifest_path = arch_dir / "manifest.json"
    if not manifest_path.is_file():
        return []
    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return []
    ids = [c["id"] for c in _iter_components(manifest.get("components")) if c.get("id")]
    if not ids:
        return []
    involved: set = set()
    for rel in manifest.get("relationships") or []:
        involved.add(rel.get("source"))
        involved.add(rel.get("target"))
    orphans = [cid for cid in ids if cid not in involved]
    share = len(orphans) / len(ids)
    if share <= 0.10:
        return []
    detail = f"{len(orphans)} of {len(ids)} components ({share:.0%}) have no relationships"
    return [{
        "check": "orphan_component_share",
        "severity": "finding",
        "summary": detail,
        "fingerprint": finding_fingerprint(slug, "orphan_component_share", f"{round(share, 2)}"),
    }]


_PAGES_FREE_FILE_LIMIT = 20_000
_SHARD_WARN_FRACTION = 0.8


def _shard_count_finding(slug: str, corpus_dir: Optional[Path]) -> list[dict]:
    """5.1: shard count and manifest size against hosting limits (a
    scalability finding). Warns at 80% of the Cloudflare Pages free-plan
    20,000-files-per-site limit (4.4), blocks (severity "blocker") at 100%."""
    arch_dir = _arch_dir(slug, corpus_dir)
    if not arch_dir.is_dir():
        return []
    file_count = sum(1 for p in arch_dir.rglob("*") if p.is_file())
    warn_at = int(_PAGES_FREE_FILE_LIMIT * _SHARD_WARN_FRACTION)
    if file_count < warn_at:
        return []
    detail = f"{file_count} files in the deploy bundle, approaching the Cloudflare Pages free-plan limit of {_PAGES_FREE_FILE_LIMIT}"
    return [{
        "check": "hosting_file_budget",
        "severity": "blocker" if file_count >= _PAGES_FREE_FILE_LIMIT else "finding",
        "summary": detail,
        "fingerprint": finding_fingerprint(slug, "hosting_file_budget", f"{file_count // 1000}k"),
    }]


def compute_findings(corpus: dict, *, corpus_dir: Optional[Path] = None) -> list[dict]:
    """The 5.1 machine-gate findings this harness can compute cheaply and
    deterministically today: every FAILing validate gate (which already covers
    unaccounted ledger rows, detect-only share, enrichment failures/quality,
    and front-door disagreement), plus zero-symbol components, orphan share,
    and the hosting file budget. NOT covered here (documented, not hidden):
    staleness surviving a refresh, and wall time/peak memory/store size versus
    last week -- both need a time series this harness's history/ cache does
    not yet retain beyond the single previous projection `diff` uses.
    """
    slug = corpus["slug"]
    findings: list[dict] = []
    for r in run_gates(corpus, corpus_dir=corpus_dir):
        if r.state != "FAIL":
            continue
        severity = "blocker" if r.name in BLOCKING_GATE_NAMES else "finding"
        findings.append({
            "check": r.name,
            "severity": severity,
            "summary": f"{r.name}: {r.detail}",
            "fingerprint": finding_fingerprint(slug, r.name, r.detail),
        })
    findings.extend(_zero_symbol_findings(slug, corpus_dir))
    findings.extend(_orphan_share_finding(slug, corpus_dir))
    findings.extend(_shard_count_finding(slug, corpus_dir))
    return findings


