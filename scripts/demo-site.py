def gate_front_door_agrees(arch_dir: Path) -> GateResult:
    """Section 2 + 3.6: front door agrees with the manifest (the S3 class).

    S3 (frontdoor.py's own docstring) was ai.json asserting `enriched: false`
    while the manifest carried ai_enhance on nearly every component, because a
    later merge step edited the manifest without calling `refresh_front_door`.
    This gate re-derives the true enrichment state from the manifest and
    compares it to ai.json's claim, and confirms every endpoint ai.json lists
    (other than templated `<...>` shard patterns) actually exists in the
    bundle. It does not (yet) re-verify every `manifest_sections[*].present`
    flag individually; the enriched-flag mismatch is the exact defect class S3
    was, and the endpoint-existence check is link integrity.
    """
    skip = _skip_if_no_manifest(arch_dir, "front_door_agrees")
    if skip:
        return skip
    ai_json_path = arch_dir / "ai.json"
    if not ai_json_path.is_file():
        return GateResult("front_door_agrees", "FAIL", f"no ai.json in {arch_dir}")
    try:
        manifest = json.loads((arch_dir / "manifest.json").read_text(encoding="utf-8"))
        ai_json = json.loads(ai_json_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        return GateResult("front_door_agrees", "FAIL", f"could not read manifest.json/ai.json: {exc}")

    manifest_enriched = bool(manifest.get("ai_enhance")) or any(
        c.get("ai_enhance") for c in _iter_components(manifest.get("components"))
    )
    claimed_enriched = (ai_json.get("dataset") or {}).get("enriched")
    if claimed_enriched != manifest_enriched:
        return GateResult(
            "front_door_agrees", "FAIL",
            f"ai.json claims dataset.enriched={claimed_enriched!r} but the manifest's actual "
            f"enrichment state is {manifest_enriched!r} (the S3 defect class)",
        )

    missing = [
        e.get("path") for e in (ai_json.get("endpoints") or [])
        if "<" not in (e.get("path") or "") and not (arch_dir / e["path"]).exists()
    ]
    if missing:
        return GateResult("front_door_agrees", "FAIL", f"ai.json lists endpoints that do not exist on disk: {missing}")

    return GateResult("front_door_agrees", "PASS", "ai.json's enrichment claim and endpoint list agree with the manifest and bundle")


