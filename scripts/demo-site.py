REQUIRED_TOP = ["slug", "subject", "track", "policy", "hosting", "cadence", "budget", "gates", "consent"]
REQUIRED_NESTED = {
    "subject": ["name", "repo", "license", "governance"],
    # "history" is deliberately not required here: it defaults to "full" (the
    # decided default) when absent, so an entry written before this field
    # existed still validates. Its VALUE, once present or defaulted, is still
    # checked below against HISTORY_VALUES.
    "policy": ["follow", "pin", "exclude"],
    "hosting": ["cf_project", "url"],
    "budget": ["max_cost_usd", "max_wall_minutes"],
    "gates": ["coverage", "max_detect_only_line_share", "min_enrichment_score"],
    "consent": ["required", "state", "contacted"],
}
FOLLOW_VALUES = {"default-branch", "latest-tag", "pinned"}
HISTORY_VALUES = {"full", "shallow"}

# Cadence granularities the harness understands. Only "weekly" appears in
# DEMO-PROGRAM.md; daily/monthly are added for a program that outlives Wave 1,
# and an unrecognized value is a hard error rather than a silent default, same
# spirit as the rest of this file's "never silently pass" rule.
CADENCE_SECONDS = {"daily": 86_400, "weekly": 7 * 86_400, "monthly": 30 * 86_400}


def validate_registry(doc) -> list[str]:
    """Structural errors in a registry entry, most specific first. Empty is valid.

    Deliberately loose on `track`: DEMO-PROGRAM.md section 2 names "Track A,
    published" and "Track B, capability-forcing targets" but the only literal
    value the design gives (4.1's worked example) is "published". Rather than
    guess Track B's exact string and reject a legitimate value, `track` is only
    required to be a non-empty string.
    """
    errors: list[str] = []
    if not isinstance(doc, dict):
        return ["registry entry must be a JSON object"]

    for key in REQUIRED_TOP:
        if key not in doc:
            errors.append(f"missing required key: {key}")
    for parent, children in REQUIRED_NESTED.items():
        node = doc.get(parent)
        if node is None:
            continue  # already reported by the top-level pass
        if not isinstance(node, dict):
            errors.append(f"{parent} must be an object")
            continue
        for child in children:
            if child not in node:
                errors.append(f"missing required key: {parent}.{child}")

    if not doc.get("slug"):
        errors.append("slug must be a non-empty string")
    if doc.get("track") is not None and not str(doc.get("track")):
        errors.append("track must be a non-empty string")

    policy = doc.get("policy") or {}
    follow = policy.get("follow")
    if follow is not None and follow not in FOLLOW_VALUES:
        errors.append(f"policy.follow must be one of {sorted(FOLLOW_VALUES)}, got {follow!r}")
    if follow == "pinned" and not policy.get("pin"):
        errors.append("policy.follow is 'pinned' but policy.pin is not set")
    history = policy.get("history", "full")
    if history not in HISTORY_VALUES:
        errors.append(f"policy.history must be one of {sorted(HISTORY_VALUES)}, got {history!r}")

    cadence = doc.get("cadence")
    if cadence is not None and cadence not in CADENCE_SECONDS:
        errors.append(f"cadence must be one of {sorted(CADENCE_SECONDS)}, got {cadence!r}")

    errors.extend(_enrichment_errors(doc.get("enrichment")))

    return errors


# The enrichment block is OPTIONAL: an entry without one runs the classic single
# bulk pass, which is what every entry did before the ladder existed. When it is
# present it is validated strictly, because a typo in a model binding or an
# iteration bound would otherwise be discovered by a run that had already spent
# most of its budget.
ENRICHMENT_PIPELINES = frozenset({"bulk", "ladder"})


def _enrichment_errors(block) -> list[str]:
    if block is None:
        return []
    if not isinstance(block, dict):
        return ["enrichment must be an object"]
    errors: list[str] = []
    pipeline = block.get("pipeline", "bulk")
    if pipeline not in ENRICHMENT_PIPELINES:
        errors.append(
            f"enrichment.pipeline must be one of {sorted(ENRICHMENT_PIPELINES)}, "
            f"got {pipeline!r}"
        )
    models = block.get("models")
    if models is not None and not isinstance(models, dict):
        errors.append("enrichment.models must be an object of rung -> binding")
    iteration = block.get("iteration")
    if iteration is not None:
        if not isinstance(iteration, dict):
            errors.append("enrichment.iteration must be an object")
        else:
            for key in ("min_rounds", "max_rounds"):
                value = iteration.get(key)
                if value is not None and (not isinstance(value, int) or value < 0):
                    errors.append(
                        f"enrichment.iteration.{key} must be a non-negative integer, "
                        f"got {value!r}"
                    )
            lo, hi = iteration.get("min_rounds"), iteration.get("max_rounds")
            if isinstance(lo, int) and isinstance(hi, int) and lo > hi:
                errors.append(
                    f"enrichment.iteration.min_rounds ({lo}) exceeds max_rounds "
                    f"({hi}), so the forced floor could never be reached"
                )
    return errors


def load_registry(slug: str, registry_dir: Optional[Path] = None) -> dict:
    """Load and validate one registry entry. `policy.history` defaults to 'full'
    (the decided default) when absent, so an older entry written before this
    field existed still loads."""
    registry_dir = registry_dir or REGISTRY_DIR
    path = registry_dir / f"{slug}.json"
    if not path.exists():
        raise FileNotFoundError(f"no registry entry for '{slug}' at {path}")
    try:
        doc = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise ValueError(f"registry entry {path} is not valid JSON: {exc}") from exc

    errors = validate_registry(doc)
    if doc.get("slug") and doc["slug"] != slug:
        errors.append(f"slug {doc['slug']!r} does not match filename '{slug}.json'")
    if errors:
        raise ValueError(f"registry entry {path} is invalid: " + "; ".join(errors))

    doc.setdefault("policy", {}).setdefault("history", "full")
    return doc


def list_registry(registry_dir: Optional[Path] = None) -> list[str]:
    """Slugs of every registered demo (a `<slug>.json` file), sorted."""
    registry_dir = registry_dir or REGISTRY_DIR
    if not registry_dir.exists():
        return []
    return sorted(p.stem for p in registry_dir.glob("*.json"))


def iter_registry(registry_dir: Optional[Path] = None) -> list[dict]:
    return [load_registry(slug, registry_dir) for slug in list_registry(registry_dir)]


def cadence_period_seconds(cadence: str) -> int:
    try:
        return CADENCE_SECONDS[cadence]
    except KeyError:
        raise ValueError(
            f"unknown cadence {cadence!r}; expected one of {sorted(CADENCE_SECONDS)}"
        ) from None


