def previous_projection(slug: str, corpus_dir: Optional[Path] = None, *, before: Optional[str] = None) -> Optional[Path]:
    before = before or _today()
    history_dir = _out_dir(slug, corpus_dir) / "history"
    if not history_dir.is_dir():
        return None
    dates = sorted(p.name for p in history_dir.iterdir() if p.is_dir() and p.name < before)
    if not dates:
        return None
    candidate = history_dir / dates[-1] / "manifest.json"
    return candidate if candidate.is_file() else None


def run_diff(corpus: dict, corpus_dir: Optional[Path] = None, runs_dir: Optional[Path] = None) -> Optional[dict]:
    """Diff the current projection against the most recent prior one recorded
    in history/. Returns None (and writes nothing) when there is no baseline
    yet -- the caller decides how to report that, matching the spec's "no
    previous run is not an error"."""
    slug = corpus["slug"]
    current = _arch_dir(slug, corpus_dir) / "manifest.json"
    if not current.is_file():
        raise FileNotFoundError(f"no analysis output for '{slug}'; run: analyze {slug}")
    previous = previous_projection(slug, corpus_dir)
    if previous is None:
        return None
    pd = _load_projection_diff()
    diff = pd.diff_projections(pd.load_projection(previous), pd.load_projection(current))
    out_path = _run_dir(slug, runs_dir=runs_dir) / "diff.json"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps(diff, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return diff


