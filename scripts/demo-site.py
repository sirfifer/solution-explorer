@dataclass
class GateResult:
    name: str
    state: str  # PASS | FAIL | NOT_IMPLEMENTED | SKIP
    detail: str = ""

    def to_dict(self) -> dict:
        return {"name": self.name, "state": self.state, "detail": self.detail}


def _skip_if_no_manifest(arch_dir: Path, gate_name: str) -> Optional[GateResult]:
    if not (arch_dir / "manifest.json").is_file():
        return GateResult(gate_name, "SKIP", f"no manifest.json at {arch_dir}; run `analyze <slug>` first")
    return None


def _iter_components(nodes) -> list[dict]:
    out: list[dict] = []
    for node in nodes or []:
        if not isinstance(node, dict):
            continue
        out.append(node)
        out.extend(_iter_components(node.get("children")))
    return out


