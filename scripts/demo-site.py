#!/usr/bin/env python3
"""SysCorpus demo-program harness (DEMO-PROGRAM.md section 4).

Orchestration over CLIs that already exist (`analyze.py`, `analyze.py enhance`,
`scripts/projection-diff.py`, `scripts/validate-publication.py`, `wrangler`).
There is no new analysis capability here, only the local execution path,
cadence bookkeeping, and the gate that decides whether a demo may go public.

Registry (`demos/registry/<slug>.json`) mirrors `tests/golden/<name>/corpus.lock`
on purpose: one committed file per outside codebase we care about (section 4.1).
The difference from a golden corpus is policy, not mechanics: a golden corpus is
FROZEN at a pinned commit so any diff is attributable to OUR engine; a demo
TRACKS upstream (`policy.follow`) so it is never stale, and the harness records
the exact resolved SHA it analyzed on every refresh.

`policy.history` (`full` | `shallow`) is an ADDITION to the 4.1 schema, not in
the original design doc. It exists because a depth-1 clone was measured to
produce a degenerate git-activity signal (DECISIONS-N3.md): every file gets
`commit_count: 1`, one author, and `cochange_pair` comes out empty, so the
Activity lens is not merely empty (honest) but populated and WRONG (a plausible
lie). `full` is the decided default: no `--depth` on the fetch, and an existing
shallow clone is repaired in place with `git fetch --unshallow` rather than left
shallow.

Layout:
    demos/registry/<slug>.json   the pinned-policy registry entry (committed)
    demos/runs/<slug>/<date>/    run records: report.json/.md, validate.json,
                                  diff.json, findings.json (committed, small,
                                  reviewable -- section 4/8 call this out
                                  explicitly: "run records committed")
    demos/hub/                   the generated static hub site (committed,
                                  regenerated by `hub`, same idiom as the
                                  repo-root architecture.json: regenerable but
                                  tracked, because it IS the reviewed artifact)
    ~/dev/.demo-corpus/<slug>/         the fetched clone (gitignored by being
                                  outside the repo entirely; override with the
                                  DEMO_CORPUS_DIR env var)
    ~/dev/.demo-corpus/_out/<slug>/    analysis output: the split projection
                                  (architecture/manifest.json + shards), the
                                  persistent fact store (index.db, warm across
                                  refreshes), the enrichment report, and a
                                  dated history/ of past manifests for `diff`.
                                  A SIBLING of the fetched source, mirroring
                                  golden-corpus.py's `_out_dir`: analyze.py's
                                  companion artifacts must never land inside the
                                  scanned corpus or the next scan counts the
                                  harness's own output as source.

Subcommands (mirroring golden-corpus.py's shape, DEMO-PROGRAM.md 4.2):
    list                 registry contents
    status               last successful run per demo, and what is due
    fetch <slug>         clone/fetch into the corpus cache, resolve the ref,
                         record the exact SHA
    analyze <slug>       v2 split projection into a persistent per-demo store
    enhance <slug>       analyze.py enhance --update, cost-ceilinged
    validate <slug>      the 3.6 checklist + the section 2 graduation gate.
                         THE ONE HARD REQUIREMENT: a gate whose instrument does
                         not exist (there are two: the classification accuracy
                         audit, 5.3, and the human-recorded license review,
                         6.1) reports NOT_IMPLEMENTED and fails the run in the
                         default strict mode. It is never silently skipped,
                         passed, or omitted. --allow-unimplemented downgrades
                         NOT_IMPLEMENTED to a warning; it never touches FAIL.
    diff <slug>          projection diff against the previous run (no previous
                         run is not an error: "no baseline", exit 0)
    deploy <slug>        wrangler pages deploy. Outward-facing, so it is a
                         DRY RUN by construction unless the DEMO_DEPLOY_ALLOW
                         env var is set (or --dry-run is passed, which always
                         wins). Nothing public happens by accident.
    report <slug>        run record, JSON and markdown, under demos/runs/
    findings <slug>      the cheap deterministic machine gates from 5.1,
                         written to findings.json with the stable fingerprint
                         from 5.2 (`demo-finding:<slug>:<check>:<hash>`).
                         Does NOT file GitHub issues. Turning a finding into an
                         issue (dedup, labels, auto-close) is a separate,
                         not-yet-built task (5.2); this only computes and
                         records the findings themselves.
    refresh <slug>       fetch -> analyze -> enhance -> validate -> diff ->
                         report -> findings, stopping at the first failure.
                         Deliberately does NOT deploy: DISCLOSURE-POLICY.md
                         requires a private preview and review before any
                         public deploy, so deploy stays a separate, deliberate
                         step even after every gate is green.
    refresh --due        every demo whose cadence is up
    hub                  regenerate demos/hub/index.html from the registry and
                         the run records: self-contained, no build step

Where this spec was silent, the choice made and why is in each function's
docstring rather than left implicit.
"""

