def _cmd_list(args: argparse.Namespace) -> int:
    corpora = iter_registry()
    if not corpora:
        print("no demos registered under demos/registry/")
        return 0
    for c in corpora:
        print(
            f"{c['slug']}: {c['subject']['name']} ({c['subject']['license']}, {c['subject']['governance']}) "
            f"track={c['track']} cadence={c['cadence']} -> {c['hosting']['url']}"
        )
    return 0


def _cmd_status(args: argparse.Namespace) -> int:
    corpora = iter_registry()
    if not corpora:
        print("no demos registered under demos/registry/")
        return 0
    now = datetime.now(timezone.utc)
    for c in corpora:
        last = last_successful_run(c["slug"])
        last_date = last.get("date") if last else None
        due = is_due(c, now=now)
        print(
            f"{c['slug']}: last successful refresh: {last_date or 'never'}; "
            f"due: {'yes' if due else 'no'} (cadence={c['cadence']})"
        )
    return 0


def _cmd_fetch(args: argparse.Namespace) -> int:
    corpus = load_registry(args.slug)
    src, sha = fetch_corpus(corpus, force=args.force)
    print(f"fetched {args.slug} @ {sha} ({corpus['policy'].get('follow')}) -> {src}")
    return 0


def _cmd_analyze(args: argparse.Namespace) -> int:
    corpus = load_registry(args.slug)
    wall_s = run_analyze(corpus)
    print(f"analyzed {args.slug} -> {_arch_dir(args.slug)} ({wall_s:.1f}s)")
    return 0


def _cmd_enhance(args: argparse.Namespace) -> int:
    corpus = load_registry(args.slug)
    rc = run_enhance(corpus, max_partitions=args.max_partitions, dry_run=args.dry_run)
    return rc


def _cmd_validate(args: argparse.Namespace) -> int:
    corpus = load_registry(args.slug)
    results = run_gates(corpus)
    for r in results:
        print(f"[{r.state:15}] {r.name}: {r.detail}")
    ok = overall_ok(results, args.allow_unimplemented)
    _write_validate_record(args.slug, results, ok)
    print()
    suffix = " (--allow-unimplemented)" if args.allow_unimplemented else ""
    print(f"OVERALL: {'PASS' if ok else 'FAIL'}{suffix}")
    return 0 if ok else 1


def _cmd_diff(args: argparse.Namespace) -> int:
    corpus = load_registry(args.slug)
    diff = run_diff(corpus)
    if diff is None:
        print(f"no baseline: no previous run recorded for '{args.slug}' yet")
        return 0
    pd = _load_projection_diff()
    print(pd.render_text(diff))
    return 0


def _cmd_bundle(args: argparse.Namespace) -> int:
    corpus = load_registry(args.slug)
    try:
        bundle = assemble_bundle(corpus, build=not args.no_build)
    except (RuntimeError, subprocess.CalledProcessError) as exc:
        print(f"error: bundle failed for '{args.slug}': {exc}", file=sys.stderr)
        return 2
    errors = bundle_safety_errors(bundle)
    for err in errors:
        print(f"  UNSAFE: {err}", file=sys.stderr)
    if errors:
        return 2
    count = sum(1 for _ in bundle.rglob("*") if _.is_file())
    print(f"bundle assembled: {bundle} ({count} files)")
    return 0


def _cmd_deploy(args: argparse.Namespace) -> int:
    corpus = load_registry(args.slug)
    bundle = _bundle_dir(args.slug)

    # Refuse before anything outward-facing. These are the obligations, not
    # preferences, so they are checked against the assembled directory even
    # when the caller believes it just built it.
    errors = bundle_safety_errors(bundle)
    if errors:
        print(f"error: refusing to deploy '{args.slug}':", file=sys.stderr)
        for err in errors:
            print(f"  {err}", file=sys.stderr)
        return 2

    cf_project = corpus["hosting"]["cf_project"]
    cmd = ["wrangler", "pages", "deploy", str(bundle), "--project-name", cf_project]

    allowed = os.environ.get(DEMO_DEPLOY_ALLOW_ENV)
    if args.dry_run or not allowed:
        reason = "--dry-run passed" if args.dry_run else f"{DEMO_DEPLOY_ALLOW_ENV} is not set"
        print(f"DRY RUN ({reason}); would run:")
        print("  " + " ".join(shlex.quote(c) for c in cmd))
        return 0

    result = subprocess.run(cmd, cwd=str(REPO_ROOT))
    return result.returncode


def _cmd_report(args: argparse.Namespace) -> int:
    corpus = load_registry(args.slug)
    report = build_report(corpus)
    run_dir = _run_dir(args.slug)
    run_dir.mkdir(parents=True, exist_ok=True)
    json_path = run_dir / "report.json"
    json_path.write_text(json.dumps(report, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    md_path = run_dir / "report.md"
    md_path.write_text(render_report_markdown(report), encoding="utf-8")
    print(f"report written: {json_path}")
    print(f"report written: {md_path}")
    return 0


def _cmd_findings(args: argparse.Namespace) -> int:
    corpus = load_registry(args.slug)
    findings = compute_findings(corpus)
    run_dir = _run_dir(args.slug)
    run_dir.mkdir(parents=True, exist_ok=True)
    out_path = run_dir / "findings.json"
    payload = {"schema": "solution-explorer/demo-findings/v1", "slug": args.slug, "date": _today(), "findings": findings}
    out_path.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(f"{len(findings)} finding(s) written to {out_path}")
    for f in findings:
        print(f"  [{f['severity']}] {f['fingerprint']}: {f['summary']}")
    return 0


def _cmd_refresh(args: argparse.Namespace) -> int:
    if args.due:
        due_slugs = [c["slug"] for c in iter_registry() if is_due(c)]
        if not due_slugs:
            print("no demos due")
            return 0
        overall = 0
        for slug in due_slugs:
            overall = _refresh_one(slug, allow_unimplemented=args.allow_unimplemented) or overall
        return overall
    if not args.slug:
        print("error: refresh requires a slug or --due", file=sys.stderr)
        return 2
    return _refresh_one(args.slug, allow_unimplemented=args.allow_unimplemented)


def _cmd_hub(args: argparse.Namespace) -> int:
    corpora = iter_registry()
    html_doc = build_hub_html(corpora)
    HUB_DIR.mkdir(parents=True, exist_ok=True)
    out_path = HUB_DIR / "index.html"
    out_path.write_text(html_doc, encoding="utf-8")
    print(f"hub written: {out_path} ({len(corpora)} demo(s))")
    return 0


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="SysCorpus demo-program harness: orchestration over analyze.py, "
        "analyze.py enhance, projection-diff.py, validate-publication.py, and wrangler.",
    )
    sub = parser.add_subparsers(dest="command", required=True)

    sub.add_parser("list", help="registry contents").set_defaults(func=_cmd_list)
    sub.add_parser("status", help="last successful run per demo and what is due").set_defaults(func=_cmd_status)

    p_fetch = sub.add_parser("fetch", help="clone/fetch into the corpus cache, resolve the ref, record the SHA")
    p_fetch.add_argument("slug")
    p_fetch.add_argument("--force", action="store_true", help="re-fetch from scratch even if already up to date")
    p_fetch.set_defaults(func=_cmd_fetch)

    p_analyze = sub.add_parser("analyze", help="v2 split projection into a persistent per-demo store")
    p_analyze.add_argument("slug")
    p_analyze.set_defaults(func=_cmd_analyze)

    p_enhance = sub.add_parser("enhance", help="analyze.py enhance --update, cost-ceilinged")
    p_enhance.add_argument("slug")
    p_enhance.add_argument("--max-partitions", type=int, default=None, help="passthrough to analyze.py enhance")
    p_enhance.add_argument("--dry-run", action="store_true", help="passthrough to analyze.py enhance")
    p_enhance.set_defaults(func=_cmd_enhance)

    p_validate = sub.add_parser("validate", help="the 3.6 checklist plus the section 2 graduation gate")
    p_validate.add_argument("slug")
    p_validate.add_argument(
        "--allow-unimplemented", action="store_true",
        help="downgrade a NOT_IMPLEMENTED gate to a warning (never a FAIL or SKIP) and exit 0",
    )
    p_validate.set_defaults(func=_cmd_validate)

    p_diff = sub.add_parser("diff", help="projection diff against the previous run")
    p_diff.add_argument("slug")
    p_diff.set_defaults(func=_cmd_diff)

    p_bundle = sub.add_parser(
        "bundle",
        help="assemble the deployable bundle (viewer + projection + preview gate + upstream license)",
    )
    p_bundle.add_argument("slug")
    p_bundle.add_argument(
        "--no-build", action="store_true",
        help="reuse an existing viewer/dist instead of running the vite build",
    )
    p_bundle.set_defaults(func=_cmd_bundle)

    p_deploy = sub.add_parser("deploy", help="wrangler pages deploy (dry run unless DEMO_DEPLOY_ALLOW is set)")
    p_deploy.add_argument("slug")
    p_deploy.add_argument("--dry-run", action="store_true", help="print the command without running it")
    p_deploy.set_defaults(func=_cmd_deploy)

    p_report = sub.add_parser("report", help="write the run record, JSON and markdown")
    p_report.add_argument("slug")
    p_report.set_defaults(func=_cmd_report)

    p_findings = sub.add_parser(
        "findings", help="compute the 5.1 machine-gate findings into findings.json (never files GitHub issues)"
    )
    p_findings.add_argument("slug")
    p_findings.set_defaults(func=_cmd_findings)

    p_refresh = sub.add_parser("refresh", help="fetch -> analyze -> enhance -> validate -> diff -> report -> findings")
    p_refresh.add_argument("slug", nargs="?", default=None)
    p_refresh.add_argument("--due", action="store_true", help="refresh every demo whose cadence is up")
    p_refresh.add_argument(
        "--allow-unimplemented", action="store_true",
        help="passthrough to validate: downgrade NOT_IMPLEMENTED gates to warnings",
    )
    p_refresh.set_defaults(func=_cmd_refresh)

    sub.add_parser("hub", help="regenerate the static hub site from the registry and run records").set_defaults(func=_cmd_hub)

    return parser


def main(argv: Optional[list[str]] = None) -> int:
    parser = _build_parser()
    args = parser.parse_args(argv)
    try:
        return args.func(args)
    except (FileNotFoundError, ValueError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    except subprocess.CalledProcessError as exc:
        print(f"error: command failed ({exc})", file=sys.stderr)
        return 2
    except subprocess.TimeoutExpired as exc:
        print(f"error: command exceeded its wall-time budget ({exc})", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
