def gate_license_review_recorded(corpus: dict) -> GateResult:
    """Section 2 (6.1): license review passed (the human-recorded half).

    6.1 item 7 calls for a recorded reviewer, date, SPDX identifier and the
    commit reviewed. That is now a real registry field, `license_review`, a
    second documented addition to the 4.1 schema alongside `policy.history`,
    and the record it points at lives under docs/publication/license-reviews/.

    The published track additionally requires the owner's countersignature.
    A license review is the legal surface of publishing someone else's code,
    and a review signed only by the tool that wants to publish is not the
    check 6.1 is asking for. Missing countersignature is a FAIL with a named
    reason, never a silent pass and never NOT_IMPLEMENTED: the instrument
    exists, the obligation is simply unmet.
    """
    review = corpus.get("license_review")
    if not isinstance(review, dict):
        return GateResult(
            "license_review_recorded", "FAIL",
            "no 'license_review' block in the registry entry; DEMO-PROGRAM.md 6.1 "
            "item 7 requires a recorded reviewer, date, SPDX identifier and commit",
        )
    missing = [k for k in ("reviewer", "date", "spdx", "record") if not review.get(k)]
    if missing:
        return GateResult(
            "license_review_recorded", "FAIL",
            f"license_review is missing {missing}",
        )
    record = REPO_ROOT / str(review["record"])
    if not record.is_file():
        return GateResult(
            "license_review_recorded", "FAIL",
            f"license_review.record points at {record}, which does not exist",
        )
    if corpus.get("track") == "published" and not review.get("countersigned_by_owner"):
        return GateResult(
            "license_review_recorded", "FAIL",
            f"license review recorded by {review['reviewer']!r} on {review['date']} "
            f"({review['spdx']}, {review['record']}) but not countersigned by the "
            f"owner; a published demo redistributes upstream text and the sign-off "
            f"is the owner's to give",
        )
    return GateResult(
        "license_review_recorded", "PASS",
        f"{review['spdx']} reviewed by {review['reviewer']!r} on {review['date']} "
        f"({review['record']})",
    )


def gate_consent_triage(consent: dict) -> GateResult:
    """Section 2: sensitivity triage clean, or outreach completed
    (DISCLOSURE-POLICY.md). Computed straight from the registry's `consent`
    block: not required is a clean pass; required is a pass only once
    `consent.state` records a cleared outcome."""
    required = consent.get("required")
    state = consent.get("state")
    if not required:
        return GateResult("consent_triage", "PASS", f"consent not required (state={state!r})")
    if state in ("approved", "cleared", "granted"):
        return GateResult("consent_triage", "PASS", f"consent recorded as {state!r}")
    return GateResult(
        "consent_triage", "FAIL",
        f"consent.required is true but consent.state is {state!r}, not a cleared "
        f"state; see DISCLOSURE-POLICY.md",
    )


def run_gates(corpus: dict, *, corpus_dir: Optional[Path] = None) -> list[GateResult]:
    """Compute every gate for one demo. Pure (no printing), so it is directly
    testable and directly reusable by `findings`."""
    slug = corpus["slug"]
    arch_dir = _arch_dir(slug, corpus_dir)
    store_path = _store_path(slug, corpus_dir)
    src = _src_dir(slug, corpus_dir)
    fetch_state = read_fetch_state(slug, corpus_dir)
    gates_cfg = corpus.get("gates", {})

    return [
        gate_split_projection(arch_dir),
        gate_coverage_complete(store_path, src),
        gate_detect_only_share(arch_dir, gates_cfg),
        gate_enrichment_quality(slug, corpus_dir, gates_cfg),
        gate_sbom_present(arch_dir),
        gate_cra_readiness_present(arch_dir),
        gate_front_door_agrees(arch_dir),
        gate_search_index(arch_dir),
        gate_publication_metadata(arch_dir, fetch_state),
        gate_upstream_license(arch_dir),
        gate_classification_accuracy_audit(),
        gate_license_review_recorded(corpus),
        gate_consent_triage(corpus.get("consent", {})),
    ]


def overall_ok(results: list[GateResult], allow_unimplemented: bool) -> bool:
    """A run is ok only when every gate PASSes, with one narrow exception:
    under --allow-unimplemented, a NOT_IMPLEMENTED gate is tolerated (it is
    reported, just not blocking). FAIL and SKIP are never tolerated by the
    flag: SKIP means a precondition step has not run yet, which is not the
    same problem --allow-unimplemented exists to solve, and FAIL means the
    subject genuinely does not meet the bar."""
    for r in results:
        if r.state == "PASS":
            continue
        if r.state == "NOT_IMPLEMENTED" and allow_unimplemented:
            continue
        return False
    return True


