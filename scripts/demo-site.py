def gate_coverage_complete(store_path: Path, src: Path) -> GateResult:
    """Section 2 + 3.6: coverage ledger complete, zero unaccounted rows.

    Cross-references a real filesystem walk against the store's coverage
    ledger, exactly the method scripts/benchmark-engine.py's `_ledger_report`
    already proved against VS Code (TASKS.md: "16,482 files walked, EVERY file
    accounted for exactly once, zero unaccounted"). Reused rather than
    reinvented: a pruned directory's single ledger row stands for everything
    beneath it (the pruned-directory ruling), so a file under an
    excluded:skipped_directory / excluded:vendored_repo row (which includes
    .git, per that same ruling) is accounted for by prefix match, not by being
    individually listed.
    """
    if not store_path.is_file():
        return GateResult("coverage_ledger_complete", "SKIP", f"no fact store at {store_path}; run `analyze <slug>` first")

    from analyzer.store import FactStore

    fs = FactStore(str(store_path))
    try:
        coverage = fs.coverage()
        summary = fs.coverage_summary()
    finally:
        fs.close()

    dir_rows = sorted(
        row["path"] for row in coverage
        if row["disposition"].startswith("excluded:skipped_directory")
        or row["disposition"].startswith("excluded:vendored_repo")
    )
    file_rows = {row["path"] for row in coverage if row["path"] not in dir_rows}

    def _under_excluded_dir(rel: str) -> bool:
        return any(rel == d or rel.startswith(d + "/") for d in dir_rows)

    walked = 0
    unaccounted = 0
    examples: list[str] = []
    for dirpath, _dirnames, filenames in os.walk(src):
        for fn in filenames:
            abs_p = Path(dirpath) / fn
            try:
                rel = abs_p.relative_to(src).as_posix()
            except ValueError:
                continue
            walked += 1
            if rel in file_rows or _under_excluded_dir(rel):
                continue
            unaccounted += 1
            if len(examples) < 5:
                examples.append(rel)

    if unaccounted:
        return GateResult(
            "coverage_ledger_complete", "FAIL",
            f"{unaccounted} of {walked} walked files are not in the coverage ledger, e.g. {examples}",
        )
    return GateResult("coverage_ledger_complete", "PASS", f"{walked} files walked, {summary.get('parsed', 0)} parsed, 0 unaccounted")


def gate_detect_only_share(arch_dir: Path, gates_cfg: dict) -> GateResult:
    """Section 2: detect-only languages under `gates.max_detect_only_line_share`
    of counted CODE lines. Full-parse vs detect-only is decided by
    FULL_PARSE_LANGS (see its docstring).

    The denominator is deliberately restricted to `analyzer.constants.CODE_LANGUAGES`
    and is the whole point of the gate. `manifest.stats.languages` counts every
    file type, so on VS Code it is 76% TypeScript and **18% JSON**, plus markdown,
    css, yaml and html. Measuring the detect-only share against that total makes
    JSON and Markdown read as "languages we cannot parse" and yields 21.9%
    against a 25% limit; measuring it against code lines yields **0.10%**.
    PREFLIGHT-MEASUREMENTS.md called this out when the numbers were first taken:
    "Use the code-only figure; the all-lines number is inflated by JSON and config
    and would give a false read."

    Getting this wrong fails safe in the wrong direction. It passes, so nobody
    looks, while sitting three points from a limit it should clear by twenty-five,
    so a subject with a little more JSON would trip a theater gate for having
    documentation."""
    skip = _skip_if_no_manifest(arch_dir, "detect_only_line_share")
    if skip:
        return skip
    manifest_path = arch_dir / "manifest.json"
    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        return GateResult("detect_only_line_share", "FAIL", f"manifest.json is not valid JSON: {exc}")

    languages = (manifest.get("stats") or {}).get("languages") or {}
    all_lines = sum(languages.values())
    code = {k: v for k, v in languages.items() if k in CODE_LANGUAGES}
    total = sum(code.values())
    if total == 0:
        return GateResult("detect_only_line_share", "PASS", "no code lines counted")
    full = sum(v for k, v in code.items() if k in FULL_PARSE_LANGS)
    detect_only = total - full
    share = detect_only / total
    limit = gates_cfg.get("max_detect_only_line_share")
    if limit is None:
        return GateResult("detect_only_line_share", "FAIL", "gates.max_detect_only_line_share is not set in the registry")
    state = "PASS" if share <= limit else "FAIL"
    non_code = all_lines - total
    return GateResult(
        "detect_only_line_share", state,
        f"{share:.2%} detect-only ({detect_only:,} of {total:,} code lines, "
        f"limit {limit:.0%}); {non_code:,} non-code lines excluded from the denominator",
    )


def gate_enrichment_quality(slug: str, corpus_dir: Optional[Path], gates_cfg: dict) -> GateResult:
    """Section 2 + 3.6, upgraded to the TRUTH instrument.

    The form scorer is a sanity FLOOR, not the gate. The calibration measured 83
    of 99 components scoring exactly 85.0 on it while nothing checked whether one
    claim was true; a gate that reads only that number certifies shape and calls
    it quality.

    So when a ladder Run Report exists, this reads what the truth instrument
    actually produced:

      * the contract census: nothing may still be asking to climb, because an
        item in the escalate state is unfinished work rather than a gap;
      * the adjudication disagreement rate: how many sampled claims independent
        adjudication would not stand behind;
      * the verify verdicts: the S2 identity surface.

    And it keeps the NOT_IMPLEMENTED discipline exactly. A ladder run whose
    adjudication sampled NOTHING has no truth instrument, and reporting PASS on
    the form floor alone would be the precise failure this gate exists to
    prevent: a green light with nothing behind it. That case is
    NOT_IMPLEMENTED, loudly, never a silent pass.

    A registry entry with no ladder falls back to the classic bulk report, which
    is what every entry did before the ladder existed.
    """
    ladder_report = enrichment_run_dir(slug) / "report.json"
    if ladder_report.is_file():
        return _gate_from_run_report(ladder_report, gates_cfg)

    report_path = _out_dir(slug, corpus_dir) / "enhance-report.json"
    if not report_path.is_file():
        return GateResult("enrichment_quality", "SKIP", f"no enrichment report at {report_path}; run `enhance <slug>` first")
    try:
        report = json.loads(report_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        return GateResult("enrichment_quality", "FAIL", f"enhance-report.json is not valid JSON: {exc}")

    failed = report.get("failed_partitions") or []
    if failed:
        return GateResult("enrichment_quality", "FAIL", f"{len(failed)} failed partition(s): {failed}")

    scorer_pass = report.get("scorer_pass")
    threshold = gates_cfg.get("min_enrichment_score")
    if scorer_pass is None:
        return GateResult("enrichment_quality", "SKIP", "enrichment report has no scorer result (a --dry-run report); run `enhance <slug>` for real")
    if scorer_pass is False:
        return GateResult("enrichment_quality", "FAIL", f"quality gate failed: {report.get('scorer_summary')}")
    return GateResult("enrichment_quality", "PASS", f"quality gate passed at threshold {threshold}: {report.get('scorer_summary')}")


# Truth-instrument bounds. Deliberately explicit rather than buried in the gate,
# because these two numbers are what "good enough to publish" means in practice
# and they should be arguable in one place.
MIN_GROUNDED_FRACTION = 0.80
MAX_DISAGREEMENT_RATE = 0.20


def _gate_from_run_report(report_path: Path, gates_cfg: dict) -> GateResult:
    try:
        report = json.loads(report_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        return GateResult("enrichment_quality", "FAIL", f"Run Report is not valid JSON: {exc}")

    identity = report.get("identity") or {}
    if identity.get("dry_run"):
        return GateResult(
            "enrichment_quality", "SKIP",
            "the Run Report is from a --dry-run ladder (no model was invoked); "
            "run `enhance <slug>` for real",
        )

    census = report.get("census") or {}
    total = int(census.get("total") or 0)
    if not total:
        return GateResult(
            "enrichment_quality", "NOT_IMPLEMENTED",
            "the ladder produced no contract census, so the truth instrument has "
            "nothing to read; this is reported rather than passed on the form floor",
        )

    unresolved = census.get("unresolved") or []
    if unresolved:
        return GateResult(
            "enrichment_quality", "FAIL",
            f"{len(unresolved)} item(s) were still asking to climb when the ladder "
            f"stopped: {unresolved[:5]}. That is unfinished work, not an honest gap",
        )

    adjudication = report.get("adjudication") or {}
    sampled = int(adjudication.get("checked") or 0)
    rate = adjudication.get("disagreement_rate")
    if not sampled or rate is None:
        return GateResult(
            "enrichment_quality", "NOT_IMPLEMENTED",
            "no grounding spot-checks were run, so the disagreement rate is "
            "undefined rather than zero and nothing has checked whether the "
            "claims are supported by their own evidence. The form scorer alone "
            "is a floor, not a quality verdict",
        )

    grounded_fraction = float(census.get("grounded_fraction") or 0.0)
    problems: list[str] = []
    if grounded_fraction < MIN_GROUNDED_FRACTION:
        problems.append(
            f"only {grounded_fraction:.1%} of items grounded "
            f"(floor {MIN_GROUNDED_FRACTION:.0%})"
        )
    if float(rate) > MAX_DISAGREEMENT_RATE:
        problems.append(
            f"adjudication would not stand behind {float(rate):.1%} of the "
            f"{sampled} claims it sampled (ceiling {MAX_DISAGREEMENT_RATE:.0%})"
        )

    # The universal gates the determination already answered mechanically are
    # read back rather than recomputed, so the gate and the Run Report cannot
    # disagree about the same run.
    unmet = [
        c.get("criterion_id")
        for c in (report.get("criteria") or [])
        if c.get("verdict") == "unmet"
    ]
    if unmet:
        problems.append("criteria not met: " + ", ".join(str(c) for c in unmet))

    identity_pass = (report.get("adjudication") or {}).get("identity") or {}
    identity_note = ""
    if identity_pass:
        verdicts = identity_pass.get("verdicts") or {}
        identity_note = (
            f"; identity verdicts {', '.join(f'{k}={v}' for k, v in sorted(verdicts.items()))}"
            if verdicts else ""
        )

    summary = (
        f"{census.get('grounded', 0)}/{total} grounded "
        f"({grounded_fraction:.1%}), disagreement {float(rate):.1%} over "
        f"{sampled} sampled claim(s){identity_note}"
    )
    if problems:
        return GateResult("enrichment_quality", "FAIL", "; ".join(problems) + f" [{summary}]")
    return GateResult("enrichment_quality", "PASS", summary)


