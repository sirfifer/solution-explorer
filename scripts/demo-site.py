def last_successful_run(slug: str, runs_dir: Optional[Path] = None) -> Optional[dict]:
    """The most recent report.json whose validate gate declared `ok`, else
    None. Iterates date directories in ascending sorted (ISO date) order so the
    last match found is the most recent."""
    runs_dir = runs_dir or RUNS_DIR
    slug_dir = runs_dir / slug
    if not slug_dir.is_dir():
        return None
    best: Optional[dict] = None
    for date_dir in sorted(p for p in slug_dir.iterdir() if p.is_dir()):
        report_path = date_dir / "report.json"
        if not report_path.is_file():
            continue
        try:
            report = json.loads(report_path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            continue
        if report.get("status") == "ok":
            best = report
    return best


def is_due(corpus: dict, runs_dir: Optional[Path] = None, *, now: Optional[datetime] = None) -> bool:
    now = now or datetime.now(timezone.utc)
    last = last_successful_run(corpus["slug"], runs_dir)
    if last is None:
        return True
    last_date_str = last.get("date")
    if not last_date_str:
        return True
    last_date = datetime.fromisoformat(last_date_str).replace(tzinfo=timezone.utc)
    return (now - last_date).total_seconds() >= cadence_period_seconds(corpus["cadence"])


