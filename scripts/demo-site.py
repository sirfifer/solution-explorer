def gate_publication_metadata(arch_dir: Path, fetch_state: Optional[dict]) -> GateResult:
    """3.6: publication.json with showcase framing, exact commit, snapshot date.

    Reuses scripts/validate-publication.py's own validate_doc/validate_bundle
    (loaded the same dynamic-import way golden-corpus.py loads projection-diff)
    rather than re-implementing the obligation checks. `publication.json`
    itself is not generated by this harness -- no subcommand in DEMO-PROGRAM.md
    4.2 creates it, so it is treated as a hand-authored artifact placed in the
    bundle before validate/deploy, same as the templates in
    docs/publication/templates/ already assume.
    """
    skip = _skip_if_no_manifest(arch_dir, "publication_metadata")
    if skip:
        return skip
    pub_path = arch_dir / "publication.json"
    if not pub_path.is_file():
        return GateResult(
            "publication_metadata", "FAIL",
            f"no publication.json in {arch_dir}; copy docs/publication/templates/"
            f"publication.showcase.json and fill it in",
        )
    try:
        doc = json.loads(pub_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        return GateResult("publication_metadata", "FAIL", f"{pub_path} is not valid JSON: {exc}")

    vp = _load_validate_publication()
    errors = vp.validate_doc(doc)
    if not errors:
        errors = vp.validate_bundle(arch_dir, doc)
    if errors:
        return GateResult("publication_metadata", "FAIL", "; ".join(errors))

    if fetch_state and fetch_state.get("resolved_sha"):
        commit = str(((doc.get("subject") or {}).get("commit")) or "")
        resolved = fetch_state["resolved_sha"]
        if commit and not (resolved.startswith(commit) or commit.startswith(resolved)):
            return GateResult(
                "publication_metadata", "FAIL",
                f"publication.json subject.commit {commit!r} does not match the resolved fetch SHA {resolved!r}",
            )

    return GateResult("publication_metadata", "PASS", f"publication.json valid, subject={(doc.get('subject') or {}).get('name')!r}")


