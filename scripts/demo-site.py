def _git(repo_dir: Path, *args: str, check: bool = True) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["git", "-C", str(repo_dir), *args], capture_output=True, text=True, check=check
    )


def _is_shallow(repo_dir: Path) -> bool:
    return _git(repo_dir, "rev-parse", "--is-shallow-repository").stdout.strip() == "true"


def _restore_dirty_tracked_files(src: Path) -> None:
    """Same defence as golden-corpus.py's fetch_corpus: a hard kill mid-run can
    leave a stray edit in a tracked file (for example a mutated fixture from an
    interrupted step); restore it so the next run never analyzes a poisoned
    tree. Untracked files (the store, history/) are left alone."""
    dirty = _git(src, "status", "--porcelain", "--untracked-files=no").stdout.strip()
    if dirty:
        _git(src, "checkout", "--", ".")


def _apply_excludes(src: Path, excludes: list[str]) -> None:
    gitignore = src / ".gitignore"
    existing = gitignore.read_text(encoding="utf-8") if gitignore.exists() else ""
    lines = existing.splitlines()
    cleaned: list[str] = []
    in_block = False
    for line in lines:
        if line.strip() == _EXCLUDE_BEGIN:
            in_block = True
            continue
        if line.strip() == _EXCLUDE_END:
            in_block = False
            continue
        if not in_block:
            cleaned.append(line)
    if excludes:
        cleaned.append(_EXCLUDE_BEGIN)
        cleaned.extend(excludes)
        cleaned.append(_EXCLUDE_END)
    gitignore.write_text("\n".join(cleaned).rstrip("\n") + "\n", encoding="utf-8")


def resolve_ref(repo_url: str, policy: dict) -> tuple[str, str]:
    """Return (ref-to-fetch, description) for `policy.follow`.

    - "pinned": the configured `policy.pin`, no network needed to resolve it.
    - "default-branch": `git ls-remote --symref <repo> HEAD`, which returns the
      branch the remote's HEAD symlinks to without a full clone.
    - "latest-tag": `git ls-remote --tags --sort=-v:refname`, picking the first
      (highest by version-sort) tag name. This is a best-effort ordering for
      semantic-version-shaped tags; the design doc does not specify a stricter
      rule (e.g. creatordate, which `ls-remote` cannot report at all), so
      version-sort is the documented choice here.
    """
    follow = policy.get("follow", "default-branch")
    if follow == "pinned":
        pin = policy.get("pin")
        if not pin:
            raise ValueError("policy.follow is 'pinned' but policy.pin is not set")
        return pin, f"pinned:{pin}"

    if follow == "default-branch":
        out = subprocess.run(
            ["git", "ls-remote", "--symref", repo_url, "HEAD"],
            capture_output=True, text=True, check=True,
        ).stdout
        for line in out.splitlines():
            if line.startswith("ref:"):
                ref = line.split()[1]
                branch = ref.rsplit("/", 1)[-1]
                return branch, f"default-branch:{branch}"
        raise RuntimeError(
            f"could not resolve the default branch of {repo_url} (no symref in ls-remote output)"
        )

    if follow == "latest-tag":
        out = subprocess.run(
            ["git", "ls-remote", "--tags", "--sort=-v:refname", repo_url],
            capture_output=True, text=True, check=True,
        ).stdout
        for line in out.splitlines():
            if not line.strip():
                continue
            _sha, ref = line.split("\t", 1)
            if ref.endswith("^{}"):
                continue  # a peeled annotated-tag marker, not the tag itself
            tag = ref[len("refs/tags/"):] if ref.startswith("refs/tags/") else ref
            return tag, f"latest-tag:{tag}"
        raise RuntimeError(f"no tags found for {repo_url}")

    raise ValueError(f"unknown policy.follow: {follow!r}")


def _write_fetch_state(
    slug: str, corpus_dir: Optional[Path], *, policy_follow: str, ref_desc: str, resolved_sha: str
) -> Path:
    path = _out_dir(slug, corpus_dir) / "fetch-state.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    state = {
        "slug": slug,
        "policy_follow": policy_follow,
        "resolved_ref": ref_desc,
        "resolved_sha": resolved_sha,
        "fetched_at": _utc_now_iso(),
    }
    path.write_text(json.dumps(state, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return path


def read_fetch_state(slug: str, corpus_dir: Optional[Path] = None) -> Optional[dict]:
    path = _out_dir(slug, corpus_dir) / "fetch-state.json"
    if not path.is_file():
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None


def fetch_corpus(corpus: dict, corpus_dir: Optional[Path] = None, *, force: bool = False) -> tuple[Path, str]:
    """Fetch/refresh the corpus clone, returning (source path, resolved SHA).

    Idempotent like golden-corpus.py's fetch_corpus, including the
    restore-dirty-tracked-files defence. The real difference: a golden corpus
    fetches one pinned SHA once and is done; a demo re-resolves `policy.follow`
    on every call (a branch or tag name can move), so unlike the golden-corpus
    pin check there is no "HEAD already matches, skip the network" short
    circuit for default-branch/latest-tag -- resolving IS the point.

    `policy.history == "full"` means a full clone: no `--depth`. When an
    existing clone is shallow and history policy is "full", it is repaired in
    place with `git fetch --unshallow` rather than left shallow (the whole
    reason this field exists; see the module docstring). The converse is never
    done: a full clone under a "shallow" policy is left full, since re-shallowing
    would only save disk at the cost of a destructive history rewrite for no
    correctness benefit.
    """
    corpus_dir = corpus_dir or CORPUS_DIR
    slug = corpus["slug"]
    repo_url = corpus["subject"]["repo"]
    policy = corpus["policy"]
    full_history = policy.get("history", "full") == "full"
    excludes = policy.get("exclude") or []
    src = _src_dir(slug, corpus_dir)

    ref_name, ref_desc = resolve_ref(repo_url, policy)

    if not force and (src / ".git").exists():
        _restore_dirty_tracked_files(src)
        currently_shallow = _is_shallow(src)
        if full_history and currently_shallow:
            _git(src, "fetch", "--unshallow")
            currently_shallow = False
        fetch_args = ["fetch"]
        # Depth-limit only when the repo is ALREADY shallow and shallow is what
        # policy wants: fetching --depth 1 into an already-full clone would
        # itself shallow it (git truncates history to the fetched tip), which
        # is exactly the reshallow the docstring above says never happens.
        if not full_history and currently_shallow:
            fetch_args += ["--depth", "1"]
        fetch_args += ["origin", ref_name]
        _git(src, *fetch_args)
        _git(src, "checkout", "-q", "--detach", "FETCH_HEAD")
    else:
        if src.exists():
            _rmtree(src)
        src.mkdir(parents=True, exist_ok=True)
        _git(src, "init", "-q")
        _git(src, "remote", "add", "origin", repo_url)
        fetch_args = ["fetch"]
        if not full_history:
            fetch_args += ["--depth", "1"]
        fetch_args += ["origin", ref_name]
        _git(src, *fetch_args)
        _git(src, "checkout", "-q", "--detach", "FETCH_HEAD")

    resolved_sha = _git(src, "rev-parse", "HEAD").stdout.strip()
    _apply_excludes(src, excludes)
    _write_fetch_state(slug, corpus_dir, policy_follow=policy.get("follow", ""), ref_desc=ref_desc, resolved_sha=resolved_sha)
    return src, resolved_sha


