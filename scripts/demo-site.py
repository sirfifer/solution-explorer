def _refresh_one(slug: str, *, allow_unimplemented: bool, corpus_dir: Optional[Path] = None) -> int:
    corpus = load_registry(slug)

    print(f"== refresh {slug}: fetch ==")
    try:
        _src, sha = fetch_corpus(corpus, corpus_dir)
    except (subprocess.CalledProcessError, RuntimeError, ValueError) as exc:
        print(f"error: fetch failed for '{slug}': {exc}", file=sys.stderr)
        return 1
    print(f"  resolved @ {sha}")

    print(f"== refresh {slug}: analyze ==")
    try:
        wall_s = run_analyze(corpus, corpus_dir)
    except (subprocess.CalledProcessError, subprocess.TimeoutExpired, FileNotFoundError) as exc:
        print(f"error: analyze failed for '{slug}': {exc}", file=sys.stderr)
        return 1
    print(f"  {wall_s:.1f}s")

    print(f"== refresh {slug}: enhance ==")
    try:
        rc = run_enhance(corpus, corpus_dir)
    except FileNotFoundError as exc:
        print(f"error: enhance failed for '{slug}': {exc}", file=sys.stderr)
        return 1
    if rc != 0:
        print(f"  enhance for '{slug}' did not pass its own gate (exit {rc}); continuing to validate, which will report it")

    print(f"== refresh {slug}: validate ==")
    results = run_gates(corpus, corpus_dir=corpus_dir)
    for r in results:
        print(f"  [{r.state:15}] {r.name}: {r.detail}")
    ok = overall_ok(results, allow_unimplemented)
    _write_validate_record(slug, results, ok)
    if not ok:
        print(f"refresh {slug}: STOPPED at validate (gate failure)", file=sys.stderr)
        return 1

    print(f"== refresh {slug}: diff ==")
    try:
        diff = run_diff(corpus, corpus_dir)
    except FileNotFoundError as exc:
        print(f"error: diff failed for '{slug}': {exc}", file=sys.stderr)
        return 1
    print("  no baseline" if diff is None else f"  has_changes={diff['has_changes']}")

    print(f"== refresh {slug}: report ==")
    report = build_report(corpus, corpus_dir=corpus_dir)
    run_dir = _run_dir(slug)
    run_dir.mkdir(parents=True, exist_ok=True)
    (run_dir / "report.json").write_text(json.dumps(report, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    (run_dir / "report.md").write_text(render_report_markdown(report), encoding="utf-8")

    print(f"== refresh {slug}: findings ==")
    findings = compute_findings(corpus, corpus_dir=corpus_dir)
    findings_payload = {
        "schema": "solution-explorer/demo-findings/v1", "slug": slug, "date": _today(), "findings": findings,
    }
    (run_dir / "findings.json").write_text(json.dumps(findings_payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(f"  {len(findings)} finding(s)")

    print(f"refresh {slug}: OK")
    return 0


