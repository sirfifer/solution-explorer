def test_publishing_someone_elses_code_requires_their_license_text_in_the_bundle(tmp_path):
    # subject.license names the identifier; this is about the TEXT. The viewer
    # renders upstream README and doc excerpts, so the bundle redistributes
    # third-party text and the notice has to travel with it.
    (tmp_path / "publication.json").write_text(json.dumps(_valid_showcase_doc()), encoding="utf-8")
    assert vp.main([str(tmp_path), "--require"]) == 1
    (tmp_path / "UPSTREAM-LICENSE.txt").write_text("MIT License ...", encoding="utf-8")
    assert vp.main([str(tmp_path), "--require"]) == 0


def test_our_own_projects_need_no_upstream_license_file(tmp_path):
    (tmp_path / "publication.json").write_text(json.dumps(_valid_owner_doc()), encoding="utf-8")
    assert vp.main([str(tmp_path), "--require"]) == 0


def test_the_bundle_check_only_runs_where_a_bundle_is_being_published(tmp_path):
    # Without --require there is no publish happening, so a missing upstream
    # license is not an error; the document itself is still validated.
    (tmp_path / "publication.json").write_text(json.dumps(_valid_showcase_doc()), encoding="utf-8")
    assert vp.main([str(tmp_path)]) == 0
